@patch
async def aclose(self:ClaudeProto):
    "Cancel in-flight handlers, pending requests, and unanswered MCP calls"
    self.broker.close()
    for t in list(self._inflight.values()): t.cancel()
    for f in self._pending.values():
        if not f.done(): f.cancel()
