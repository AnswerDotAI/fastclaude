@patch
def _attach(self:ToolBroker, call):
    slot = self._slot(call)
    if slot is None: raise ValueError(f'unexpected MCP tool call: {call.name} {call.arguments}')
    call.slot = slot
    slot.call = call
    if slot.result is not None: call.future.set_result(slot.result)

