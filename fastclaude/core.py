async def _reap_process(proc):
    if await _wait_process(proc): return
    with suppress(ProcessLookupError): proc.terminate()
    if await _wait_process(proc): return
    with suppress(ProcessLookupError): proc.kill()
    with suppress(Exception): await proc.wait()

